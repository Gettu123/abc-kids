const dict: Record<Lang, Record<keyof typeof es, string>> = { "es-VE": es, pt };

export type I18nKey = keyof typeof es;

export function t(lang: Lang, key: I18nKey, vars?: Record<string, string | number>) {
  let s: string = dict[lang][key] ?? dict["es-VE"][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function kidWord(lang: Lang, gender: Gender) {
  if (lang === "pt") return gender === "boy" ? "menino" : "menina";
  return gender === "boy" ? "chamo" : "chama";
}

export function hiName(lang: Lang, gender: Gender, name: string) {
  return t(lang, gender === "boy" ? "hiNameBoy" : "hiNameGirl", { name });
}

