export function randomPraise(lang: Lang, name: string, gender: Gender) {
  const key = PRAISE_KEYS[Math.floor(Math.random() * PRAISE_KEYS.length)];
  return t(lang, key, { name, kid: kidWord(lang, gender) });
}

